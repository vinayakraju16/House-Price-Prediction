"""Model loading, input validation, and prediction logic."""

from functools import lru_cache
from hashlib import sha256
import json
from pathlib import Path
from urllib.error import URLError
from urllib.parse import urlencode
from urllib.request import urlopen

import joblib
import numpy as np
import pandas as pd
from django.conf import settings
from django.core.cache import cache


FEATURE_NAMES = (
    "MasVnrArea", "SaleType_WD", "OverallQual", "OverallCond",
    "ExterQual_Gd", "ExterCond_Fa", "BsmtUnfSF", "BsmtFinType1_LwQ",
    "LotArea", "YearBuilt", "BsmtFinSF1", "TotRmsAbvGrd",
    "GarageCars", "GarageArea",
)

INTEGER_FEATURES = {
    "SaleType_WD", "OverallQual", "OverallCond", "ExterQual_Gd",
    "ExterCond_Fa", "BsmtFinType1_LwQ", "YearBuilt", "TotRmsAbvGrd",
    "GarageCars",
}

# Held-out RMSE recorded by ml/train.py for the deployed Gradient Boosting model.
# This is an error-based estimate band, not a guaranteed appraisal interval.
MODEL_RMSE = 38_076.30


class PredictionInputError(ValueError):
    """Raised when a prediction request is incomplete or invalid."""


@lru_cache(maxsize=1)
def load_models():
    """Load the deployed ensemble once per web process."""
    model_path = Path(settings.BASE_DIR) / "mlmodels" / "trained_models.pkl"
    model_bundle = joblib.load(model_path)
    if not isinstance(model_bundle, dict):
        raise RuntimeError("The model artifact must contain a dictionary of models.")

    elastic_net = model_bundle.get("best_elastic_net")
    gradient_boost = model_bundle.get("best_gboost")
    if elastic_net is None or gradient_boost is None:
        raise RuntimeError("The model artifact is missing the required ensemble models.")
    return elastic_net, gradient_boost


@lru_cache(maxsize=1)
def model_metadata():
    """Return safe, user-facing metadata generated by the training script."""
    metadata_path = Path(settings.BASE_DIR) / "mlmodels" / "metadata.json"
    with metadata_path.open(encoding="utf-8") as metadata_file:
        return json.load(metadata_file)


@lru_cache(maxsize=1)
def harris_model():
    return joblib.load(Path(settings.BASE_DIR) / "mlmodels" / "harris_county_2026_model.joblib")


@lru_cache(maxsize=1)
def harris_metadata():
    with (Path(settings.BASE_DIR) / "mlmodels" / "harris_county_2026_metadata.json").open(encoding="utf-8") as metadata_file:
        return json.load(metadata_file)


def build_input_frame(payload):
    if not isinstance(payload, dict):
        raise PredictionInputError("The request body must be a JSON object.")

    missing = [name for name in FEATURE_NAMES if name not in payload]
    if missing:
        raise PredictionInputError(f"Missing features: {', '.join(missing)}")

    values = {}
    for name in FEATURE_NAMES:
        try:
            value = float(payload[name])
        except (TypeError, ValueError):
            raise PredictionInputError(f"{name} must be a number.") from None
        if value < 0:
            raise PredictionInputError(f"{name} cannot be negative.")
        if name in INTEGER_FEATURES and not value.is_integer():
            raise PredictionInputError(f"{name} must be a whole number.")
        values[name] = int(value) if name in INTEGER_FEATURES else value

    if not 1 <= values["OverallQual"] <= 10:
        raise PredictionInputError("OverallQual must be between 1 and 10.")
    if not 1 <= values["OverallCond"] <= 10:
        raise PredictionInputError("OverallCond must be between 1 and 10.")
    for name in ("SaleType_WD", "ExterQual_Gd", "ExterCond_Fa", "BsmtFinType1_LwQ"):
        if values[name] not in (0, 1):
            raise PredictionInputError(f"{name} must be 0 or 1.")

    return pd.DataFrame([values], columns=FEATURE_NAMES)


def predict_price(payload):
    features = build_input_frame(payload)
    elastic_net, gradient_boost = load_models()
    # The reproducible evaluation in ml/train.py selects Gradient Boosting as
    # the deployed model. Its held-out error is lower than the 50/50 ensemble.
    return float(gradient_boost.predict(features)[0])


def estimate_details(payload):
    """Return a prediction, transparent uncertainty band, and input confidence."""
    features = build_input_frame(payload)
    _, gradient_boost = load_models()
    prediction = float(gradient_boost.predict(features)[0])
    values = features.iloc[0]
    metadata = model_metadata()
    unusual = [
        name for name, bounds in metadata["typical_feature_ranges"].items()
        if not bounds["minimum"] <= values[name] <= bounds["maximum"]
    ]
    if len(unusual) == 0:
        level, message = "High", "All entered values are within typical ranges seen during training."
    elif len(unusual) <= 2:
        level, message = "Medium", "Some entered values are uncommon in the training data."
    else:
        level, message = "Low", "Several entered values are outside typical training ranges."
    return {
        "prediction": prediction,
        "range": {
            "low": max(0, prediction - MODEL_RMSE),
            "high": prediction + MODEL_RMSE,
            "margin": MODEL_RMSE,
        },
        "confidence": {"level": level, "message": message, "unusual_features": unusual},
        "model_factors": metadata.get("feature_importance", [])[:3],
    }


def harris_estimate(payload):
    """Estimate 2026 HCAD market value using the separate Harris County model."""
    metadata = harris_metadata()
    if not isinstance(payload, dict):
        raise PredictionInputError("The request body must be a JSON object.")
    missing = [feature for feature in metadata["features"] if feature not in payload]
    if missing:
        raise PredictionInputError(f"Missing Harris County fields: {', '.join(missing)}")

    values = {}
    for feature in metadata["categorical_features"]:
        value = payload[feature]
        values[feature] = "__missing__" if value is None or str(value).strip() == "" else str(value).strip()
    for feature in metadata["numeric_features"]:
        try:
            values[feature] = float(payload[feature])
        except (TypeError, ValueError):
            raise PredictionInputError(f"{feature} must be a number.") from None
        if values[feature] < 0:
            raise PredictionInputError(f"{feature} cannot be negative.")

    predicted = float(np.expm1(harris_model().predict(pd.DataFrame([values], columns=metadata["features"]))[0]))
    percentage_error = metadata["metrics"]["median_absolute_percentage_error"] / 100
    margin = predicted * percentage_error
    return {
        "prediction": predicted,
        "range": {"low": max(0, predicted - margin), "high": predicted + margin, "margin": margin},
        "confidence": {
            "level": "Medium",
            "message": "Based on a model trained on 2024–2025 HCAD records and evaluated against 2026 records.",
        },
        "disclaimer": metadata["target_disclaimer"],
    }


def market_context(address):
    """Fetch address and market context without making a prediction depend on it."""
    if not address or not isinstance(address, str):
        return {"available": False, "message": "Add a U.S. address for market context."}
    normalized_address = address.strip()
    cache_key = f"market-context:{sha256(normalized_address.lower().encode()).hexdigest()}"
    cached = cache.get(cache_key)
    if cached is not None:
        return cached
    context = _market_context_for_address(normalized_address)
    cache.set(cache_key, context, timeout=60 * 60 * 6)
    return context


def _market_context_for_address(address):
    try:
        geography = _geocode(address)
    except (URLError, TimeoutError, ValueError, KeyError, json.JSONDecodeError):
        return {"available": False, "message": "We could not look up this address right now."}

    context = {
        "available": True,
        "address": geography["matched_address"],
        "county": geography["county_name"],
        "state": geography["state"],
        "updated_at": "Live Census geocoder result",
    }
    if settings.CENSUS_API_KEY:
        try:
            context["county_median_home_value"] = _county_home_value(geography)
            context["updated_at"] = "ACS 2024 5-year estimate"
        except (URLError, TimeoutError, ValueError, KeyError, IndexError, json.JSONDecodeError):
            context["market_data_note"] = "Address found; Census market data is temporarily unavailable."
    else:
        context["market_data_note"] = "Add CENSUS_API_KEY to show county housing data."

    if settings.FRED_API_KEY:
        try:
            context["mortgage_rate"] = _mortgage_rate()
        except (URLError, TimeoutError, ValueError, KeyError, IndexError, json.JSONDecodeError):
            context["mortgage_rate_note"] = "Mortgage-rate data is temporarily unavailable."
    return context


def _get_json(url, params):
    request_url = f"{url}?{urlencode(params)}"
    with urlopen(request_url, timeout=5) as response:
        return json.loads(response.read().decode("utf-8"))


def _geocode(address):
    result = _get_json("https://geocoding.geo.census.gov/geocoder/geographies/onelineaddress", {
        "address": address, "benchmark": "Public_AR_Current", "vintage": "Current_Current", "format": "json"
    })["result"]["addressMatches"]
    if not result:
        raise ValueError("No matching address")
    match = result[0]
    components = match["addressComponents"]
    county = match["geographies"]["Counties"][0]
    return {
        "matched_address": match["matchedAddress"],
        "state": components["state"],
        "state_fips": county["STATE"],
        "county_fips": county["COUNTY"],
        "county_name": county["NAME"],
    }


def _county_home_value(geography):
    response = _get_json("https://api.census.gov/data/2024/acs/acs5", {
        "get": "NAME,B25077_001E", "for": f"county:{geography['county_fips']}",
        "in": f"state:{geography['state_fips']}", "key": settings.CENSUS_API_KEY,
    })
    return int(response[1][1])


def _mortgage_rate():
    response = _get_json("https://api.stlouisfed.org/fred/series/observations", {
        "series_id": "MORTGAGE30US", "api_key": settings.FRED_API_KEY,
        "file_type": "json", "sort_order": "desc", "limit": 1,
    })
    return float(response["observations"][0]["value"])
